    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed

        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da "
                + "obrisete ovu knjigu?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteKnjiga(kg);
                FormPretragaKnjige fp = (FormPretragaKnjige) getParent();
                fp.refreshTable();
                Session.getInstance().getMf().popuniKnjige();
                JOptionPane.showMessageDialog(this, "Uspesno obrisana knjiga.");
                this.dispose();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Ne mozete da obrisete ovu "
                        + "knjigu jer je bila porucena!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
//                JOptionPane.showMessageDialog(this,
//                        "Sistem ne moze da obrise knjigu!", "Obavestenje",
//                        JOptionPane.ERROR_MESSAGE);
//                Logger.getLogger(FormDetaljiKnjige.class.getName()).log(Level.SEVERE, null, ex);
            }
        }

    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed

        try {

            if (txtProizvodjac.getText().isEmpty() || txtCena.getText().isEmpty()
                    || txtOpis.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }

            String proizvodjac = txtProizvodjac.getText();
            String opis = txtOpis.getText();
            double cena = Double.parseDouble(txtCena.getText());

            kg.setProizvodjac(proizvodjac);
            kg.setOpis(opis);
            kg.setCena(cena);

            ClientController.getInstance().updateKnjiga(kg);
            FormPretragaKnjige fp = (FormPretragaKnjige) getParent();
            fp.refreshTable();
            Session.getInstance().getMf().popuniKnjige();
            JOptionPane.showMessageDialog(this, "Uspesno izmenjena knjiga.");
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Greska", JOptionPane.ERROR_MESSAGE);
//            Logger.getLogger(FormDetaljiKnjige.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnIzmeniActionPerformed


