    private void btnDetaljiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetaljiActionPerformed
        int row = tblKnjige.getSelectedRow();

        if (row >= 0) {
            try {
                Knjiga izabranaKnjiga
                        = ((TableModelKnjige) tblKnjige
                                .getModel()).getSelectedKnjiga(row);
                ArrayList<Knjiga> knjigaIzBaze
                        = ClientController.getInstance().getAllKnjiga(izabranaKnjiga);

//                JOptionPane.showMessageDialog(this, "Sistem je nasao knjigu!");
                new FormDetaljiKnjige(this, true, knjigaIzBaze.get(0)).setVisible(true);
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Sistem ne moze da nadje knjigu!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);
                Logger.getLogger(FormPretragaKnjige.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_btnDetaljiActionPerformed

