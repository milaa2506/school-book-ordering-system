    private void postaviDatume() {
        SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
        Calendar kalendar = Calendar.getInstance();
        txtDatumPorudzbine.setText(sdf.format(kalendar.getTime()));
        kalendar.add(Calendar.DAY_OF_MONTH, 3);
        txtDatumIsporuke.setText(sdf.format(kalendar.getTime()));
    }

    private void izracunajIznosStavke() {
        if (cmbKnjiga.getSelectedItem() instanceof Knjiga) {
            Knjiga knjiga = (Knjiga) cmbKnjiga.getSelectedItem();
            int kolicina = (Integer) spnKolicina.getValue();
            txtIznosStavke.setText(kolicina * knjiga.getCena() + " din");
        } else {
            txtIznosStavke.setText("");
        }
    }

    private void osveziObracun() {
        TableModelStavkePorudzbine tm = (TableModelStavkePorudzbine) tblStavke.getModel();
        iznosBezPopusta = tm.vratiIznosBezPopusta();

        popust = 0;
        if (cmbKupac.getSelectedItem() instanceof Kupac) {
            popust = ((Kupac) cmbKupac.getSelectedItem()).getKategorija().getPopust();
        }

        ukupanIznos = Porudzbina.izracunajUkupanIznos(iznosBezPopusta, popust);
        double iznosPopusta = Math.round((iznosBezPopusta - ukupanIznos) * 100) / 100.0;

        txtIznosBezPopusta.setText(iznosBezPopusta + " din");
        txtPopust.setText((int) popust + "% (-" + iznosPopusta + " din)");
        txtUkupanIznos.setText(ukupanIznos + " din");
    }

    public void popuniKupce() {
        try {
            ArrayList<Kupac> kupci = ClientController.getInstance()
                    .getAllKupac(new Kupac(-1, "", "", "", "", new Kategorija(-1, "")));

            cmbKupac.removeAllItems();

            for (Kupac kupac : kupci) {
                cmbKupac.addItem(kupac);
            }

        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void popuniKnjige() {
        try {
            ArrayList<Knjiga> knjige = ClientController.getInstance()
                    .getAllKnjiga(new Knjiga(-1, "", "", "", 0));

            cmbKnjiga.removeAllItems();

            for (Knjiga knjiga : knjige) {
                cmbKnjiga.addItem(knjiga);
            }

        } catch (Exception ex) {
            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

