    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed

        if (!(cmbKnjiga.getSelectedItem() instanceof Knjiga)) {
            JOptionPane.showMessageDialog(this, "Morate izabrati knjigu!");
            return;
        }

        Knjiga knjiga = (Knjiga) cmbKnjiga.getSelectedItem();
        int kolicina = (Integer) spnKolicina.getValue();
        double iznos = kolicina * knjiga.getCena();

        StavkaPorudzbine sp = new StavkaPorudzbine(null, -1, kolicina, knjiga.getCena(),
                iznos, knjiga);

        TableModelStavkePorudzbine tm = (TableModelStavkePorudzbine) tblStavke.getModel();
        tm.dodajStavku(sp);

        spnKolicina.setValue(1);
        osveziObracun();
    }//GEN-LAST:event_btnDodajActionPerformed

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        int row = tblStavke.getSelectedRow();

        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Izaberite stavku koju zelite da obrisete!");
            return;
        }

        TableModelStavkePorudzbine tm = (TableModelStavkePorudzbine) tblStavke.getModel();
        tm.obrisiStavku(row);

        osveziObracun();
    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed

        try {
            if (txtDatumIsporuke.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Morate uneti datum isporuke!");
                return;
            }

            if (!(cmbKupac.getSelectedItem() instanceof Kupac)) {
                JOptionPane.showMessageDialog(this, "Morate izabrati kupca!");
                return;
            }

            Kupac kupac = (Kupac) cmbKupac.getSelectedItem();
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumIsporuke = sdf.parse(txtDatumIsporuke.getText());

            TableModelStavkePorudzbine tm = (TableModelStavkePorudzbine) tblStavke.getModel();
            osveziObracun();

            Porudzbina p = new Porudzbina(-1, new Date(), datumIsporuke,
                    iznosBezPopusta, popust, ukupanIznos, kupac, ulogovani, tm.getLista());

            ClientController.getInstance().addPorudzbina(p);
            postaviDatume();
            tm.getLista().clear();
            tm.fireTableDataChanged();
            osveziObracun();
            JOptionPane.showMessageDialog(this, "Sistem je zapamtio porudzbinu!");

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
            //            Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

